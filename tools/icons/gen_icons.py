#!/usr/bin/env python3
"""Salin SEMUA ikon vektor Android (res/drawable/ic_*.xml) apa adanya ke desktop → Controls/DepupIcons.g.cs.
Jalankan ulang setiap ikon Android berubah:  python3 tools/icons/gen_icons.py <folder res/drawable Android>"""
import sys, os, re, xml.etree.ElementTree as ET
A = '{http://schemas.android.com/apk/res/android}'
src = sys.argv[1] if len(sys.argv) > 1 else os.path.expanduser('~/Documents/DepupOffice-main/app/src/main/res/drawable')
colors = {'@color/brand': '#FF0037FF', '@color/ic_launcher_background': '#FF0037FF'}
out = []
for fn in sorted(os.listdir(src)):
    if not (fn.startswith('ic_') and fn.endswith('.xml')): continue
    root = ET.parse(os.path.join(src, fn)).getroot()
    if root.tag != 'vector': continue
    vw, vh = float(root.get(A+'viewportWidth')), float(root.get(A+'viewportHeight'))
    paths = []
    def walk(node, m):
        for ch in node:
            if ch.tag == 'group':
                tx, ty = float(ch.get(A+'translateX', 0)), float(ch.get(A+'translateY', 0))
                sx, sy = float(ch.get(A+'scaleX', 1)), float(ch.get(A+'scaleY', 1))
                px, py = float(ch.get(A+'pivotX', 0)), float(ch.get(A+'pivotY', 0))
                # Android: translate(tx+px, ty+py) · scale(sx, sy) · translate(-px, -py), digabung dengan induk
                a, b, c, d, e, f = m
                ox, oy = tx + px - sx * px, ty + py - sy * py
                walk(ch, (a * sx, b * sx, c * sy, d * sy, a * ox + c * oy + e, b * ox + d * oy + f))
            elif ch.tag == 'path':
                col = ch.get(A+'fillColor', '#FF000000')
                col = colors.get(col, col)
                if len(col) == 7: col = '#FF' + col[1:]
                # warna tema (@color/…) & #111111 = diwarnai ulang (tint), seperti di Android
                tint = col.startswith('@') or col.upper() in ('#FF111111', '#FF000000')
                paths.append((ch.get(A+'pathData'), ch.get(A+'fillType') == 'evenOdd', None if tint else col, m))
    walk(root, (1, 0, 0, 1, 0, 0))
    out.append((fn[3:-4], vw, vh, paths))

def cs(s): return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'
L = ['// <auto-generated> tools/icons/gen_icons.py — ikon vektor DepUp Office Android (Depup Solid), JANGAN diedit manual.',
     'namespace DepupOfficeDesktop.Controls', '{', '    internal static partial class DepupIcons', '    {',
     '        private static readonly System.Collections.Generic.Dictionary<string, Vec> Data = new()', '        {']
for name, vw, vh, paths in out:
    ps = ', '.join('new P(%s, %s, %s, new float[] { %s })' % (cs(d), 'true' if eo else 'false', cs(c) if c else 'null',
                   ', '.join('%gf' % v for v in m)) for d, eo, c, m in paths)
    L.append('            [%s] = new Vec(%gf, %gf, new[] { %s }),' % (cs(name), vw, vh, ps))
L += ['        };', '    }', '}', '']
dst = os.path.join(os.path.dirname(__file__), '..', '..', 'DepupOfficeDesktop', 'Controls', 'DepupIcons.g.cs')
open(dst, 'w').write('\n'.join(L))
print(len(out), 'ikon →', os.path.normpath(dst))
